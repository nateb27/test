/**
 * Offline tools for the rendered art (runs the real renderer in Node through Vite's SSR loader).
 *
 *   node scripts/art-tool.mjs palette            # fit the shared 240-colour palette, write paletteData.ts
 *   node scripts/art-tool.mjs sheet [filter] [out.png] [scale]
 *                                                # render jobs whose JSON matches `filter` onto grass, save a PNG
 *   node scripts/art-tool.mjs time               # time every job (single thread)
 *
 * `npm run art:palette` runs the first. Re-run it when materials or lighting change noticeably.
 */

import { writeFileSync } from 'node:fs';
import { Buffer } from 'node:buffer';
import { deflateSync } from 'node:zlib';
import process from 'node:process';
import { createServer } from 'vite';

const [cmd = 'sheet', filter = '', outArg, scaleArg] = process.argv.slice(2);

const server = await createServer({ server: { middlewareMode: true, hmr: false }, appType: 'custom', logLevel: 'error', optimizeDeps: { noDiscovery: true } });
const jobsMod = await server.ssrLoadModule('/src/client/art/rendered/jobs.ts');
const renderMod = await server.ssrLoadModule('/src/client/art/rendered/render.ts');
const quantMod = await server.ssrLoadModule('/src/client/art/rendered/quantize.ts');
const terrMod = await server.ssrLoadModule('/src/client/art/rendered/terrainTex.ts');
const { allJobs, runJob } = jobsMod;
const { runToEnd } = renderMod;

function crc32(buf) {
  let c;
  const table = (crc32.t ??= Array.from({ length: 256 }, (_, n) => {
    c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    return c >>> 0;
  }));
  let crc = 0xffffffff;
  for (const b of buf) crc = table[(crc ^ b) & 255] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}
function png(w, h, rgba) {
  const raw = Buffer.alloc((w * 4 + 1) * h);
  for (let y = 0; y < h; y++) {
    raw[y * (w * 4 + 1)] = 0;
    Buffer.from(rgba.buffer, rgba.byteOffset + y * w * 4, w * 4).copy(raw, y * (w * 4 + 1) + 1);
  }
  const chunk = (type, data) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(td));
    return Buffer.concat([len, td, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
}

const now = () => Number(process.hrtime.bigint() / 1000000n);

if (cmd === 'time') {
  let total = 0;
  for (const j of allJobs()) {
    const t = now();
    runToEnd(runJob(j));
    const dt = now() - t;
    total += dt;
    console.log(JSON.stringify(j).padEnd(60), dt, 'ms');
  }
  console.log('total', total, 'ms');
} else if (cmd === 'palette') {
  const hist = new Uint32Array(32768);
  const jobs = allJobs().filter((j) => j.type !== 'unitIcon' && (j.type !== 'unit' || j.state === 'walk'));
  const t = now();
  for (const j of jobs) {
    const r = runToEnd(runJob(j, true));
    for (const s of r.sprites) quantMod.addToHistogram(hist, s.sprite.rawRgb, 3, s.sprite.rawMask);
    // Terrain covers most of the screen: weight it up.
    if (r.terrain !== null) for (let k = 0; k < 3; k++) quantMod.addToHistogram(hist, r.terrain.rawRgb, 3);
    process.stdout.write('.');
  }
  const pal = quantMod.medianCut(hist, quantMod.SHARED_COLOURS);
  const list = Array.from(pal);
  const rows = [];
  for (let i = 0; i < list.length; i += 24) rows.push('  ' + list.slice(i, i + 24).join(', ') + ',');
  writeFileSync('src/client/art/rendered/paletteData.ts', `/** Generated by \`npm run art:palette\` (scripts/art-tool.mjs) from representative renders. Do not edit by hand. */\nexport const PALETTE_RGB: readonly number[] = [\n${rows.join('\n')}\n];\n`);
  console.log(`\n${pal.length / 3} colours in ${now() - t} ms`);
} else {
  // Contact sheet on a grass background.
  const scale = Number(scaleArg ?? 1);
  const out = outArg ?? '/tmp/art-sheet.png';
  const jobs = allJobs().filter((j) => JSON.stringify(j).includes(filter));
  const sprites = [];
  const t = now();
  for (const j of jobs) {
    const t0 = now();
    const r = runToEnd(runJob(j));
    for (const s of r.sprites) if (s.name.includes(process.env.NAME ?? "")) sprites.push(s);
    console.log(JSON.stringify(j), now() - t0, 'ms');
  }
  console.log('render', now() - t, 'ms');
  const grass = runToEnd(terrMod.renderTerrainTex('grass'));
  const pad = 6;
  const maxW = 1600;
  let x = pad;
  let y = pad;
  let rowH = 0;
  const place = [];
  for (const s of sprites) {
    const w = s.sprite.w;
    const h = s.sprite.h;
    if (x + w + pad > maxW) {
      x = pad;
      y += rowH + pad;
      rowH = 0;
    }
    place.push([s, x, y]);
    x += w + pad;
    rowH = Math.max(rowH, h);
  }
  const W = maxW;
  const H = y + rowH + pad;
  const img = new Uint8ClampedArray(W * H * 4);
  for (let py = 0; py < H; py++)
    for (let px = 0; px < W; px++) {
      const si = ((px % grass.w) + grass.w * (py % grass.h)) * 4;
      const di = (px + W * py) * 4;
      img[di] = grass.rgba[si];
      img[di + 1] = grass.rgba[si + 1];
      img[di + 2] = grass.rgba[si + 2];
      img[di + 3] = 255;
    }
  for (const [s, ox, oy] of place) {
    const sp = s.sprite;
    for (let yy = 0; yy < sp.th; yy++)
      for (let xx = 0; xx < sp.tw; xx++) {
        const si = (xx + sp.tw * yy) * 4;
        const a = sp.rgba[si + 3] / 255;
        if (a <= 0) continue;
        const dx = ox + sp.tx + xx;
        const dy = oy + sp.ty + yy;
        if (dx >= W || dy >= H) continue;
        const di = (dx + W * dy) * 4;
        for (let k = 0; k < 3; k++) img[di + k] = img[di + k] * (1 - a) + sp.rgba[si + k] * a;
      }
  }
  let outImg = img;
  let OW = W;
  let OH = H;
  if (scale > 1) {
    OW = W * scale;
    OH = H * scale;
    outImg = new Uint8ClampedArray(OW * OH * 4);
    for (let py = 0; py < OH; py++)
      for (let px = 0; px < OW; px++) {
        const si = (Math.floor(px / scale) + W * Math.floor(py / scale)) * 4;
        const di = (px + OW * py) * 4;
        outImg[di] = img[si];
        outImg[di + 1] = img[si + 1];
        outImg[di + 2] = img[si + 2];
        outImg[di + 3] = 255;
      }
  }
  writeFileSync(out, png(OW, OH, outImg));
  console.log('wrote', out, OW, 'x', OH);
}
await server.close();
